const MAP = {};
DAYS.forEach((d) => { MAP[d[0]] = { date: d[0], name: d[1], off: d[2] }; });

// 节日正日：当天显示节日名，其余放假日只显示「休」，调休日只显示「班」
const FESTIVAL_DAY = {
  元旦: '2026-01-01',
  春节: '2026-02-17',
  清明节: '2026-04-05',
  劳动节: '2026-05-01',
  端午节: '2026-06-19',
  中秋节: '2026-09-25',
  国庆节: '2026-10-01'
};

function holidayOf(dateStr) {
  const item = MAP[dateStr];
  if (!item) return null;
  return Object.assign({}, item, { festival: FESTIVAL_DAY[item.name] === dateStr });
}

module.exports = { holidayOf };
